// Build step: parses src/content/blog/*.md and bakes the result into
// src/lib/generated-posts.ts, which is what the app actually imports at
// runtime. Cloudflare Workers has no filesystem access at request time, so
// blog.ts can't read these .md files directly once deployed — this script
// runs during `npm run build` (locally, where fs works) and produces a
// plain JS module instead.
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";
import { micromark } from "micromark";
import { gfm, gfmHtml } from "micromark-extension-gfm";

const BLOG_DIR = path.join(process.cwd(), "src/content/blog");
const OUT_FILE = path.join(process.cwd(), "src/lib/generated-posts.ts");

const slugs = fs
  .readdirSync(BLOG_DIR)
  .filter((f) => f.endsWith(".md"))
  .map((f) => f.replace(/\.md$/, ""));

const posts = slugs.map((slug) => {
  const raw = fs.readFileSync(path.join(BLOG_DIR, `${slug}.md`), "utf8");
  const { data, content } = matter(raw);
  const rawHtml = micromark(content, {
    extensions: [gfm()],
    htmlExtensions: [gfmHtml()],
  });
  // Every link in post body content opens in a new tab, per Joe's request —
  // readers shouldn't lose their place in the post when they follow a link.
  const withNewTabLinks = rawHtml.replace(
    /<a href="/g,
    '<a target="_blank" rel="noopener noreferrer" href="',
  );
  // Every post body opens with a heading that just repeats the frontmatter
  // title (e.g. "<h2><strong>The Hero's Journey</strong></h2>") — the page
  // template already renders that title as its own <h1>, so drop the
  // duplicate here rather than showing it twice. Same story for the "By Joe
  // Caruso Stories" byline right after it — the page renders that alongside
  // the date now, as one combined byline/date line under the title.
  const html = withNewTabLinks
    .replace(/^<h2>.*?<\/h2>\n?/, "")
    .replace(/^<h4>By Joe Caruso Stories<\/h4>\n?/, "");

  return {
    slug,
    title: data.title,
    date: data.date,
    excerpt: data.excerpt,
    coverImage: data.coverImage ?? null,
    html,
  };
});

posts.sort((a, b) => (a.date < b.date ? 1 : -1));

const banner =
  "// Auto-generated by scripts/generate-blog-data.mjs — do not edit directly.\n" +
  "// Edit the source files in src/content/blog/ and re-run `npm run build`.\n\n";

const body =
  "export type GeneratedPost = {\n" +
  "  slug: string;\n" +
  "  title: string;\n" +
  "  date: string;\n" +
  "  excerpt: string;\n" +
  "  coverImage: string | null;\n" +
  "  html: string;\n" +
  "};\n\n" +
  `export const GENERATED_POSTS: GeneratedPost[] = ${JSON.stringify(posts, null, 2)};\n`;

fs.writeFileSync(OUT_FILE, banner + body);
console.log(`Generated ${posts.length} posts -> ${OUT_FILE}`);
